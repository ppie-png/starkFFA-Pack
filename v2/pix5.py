def width(text, gap=1):
    return sum(len(F[c][0]) for c in text) + gap * (len(text) - 1)
def draw(im, x, y, text, color, gap=1):
    for c in text:
        g = F[c]
        for yy, row in enumerate(g):
            for xx, ch in enumerate(row):
                if ch == "#": im.putpixel((x + xx, y + yy), color)
        x += len(g[0]) + gap
    return x
