"""Single source of truth for the animated name styles: exact marker colours (8 per style, ping-pong gradient as the
fallback look) + the shader kind. Writes the GLSL table and the Java table so both always match."""
import re, glob, json
KINDS = ['glint', 'heartbeat', 'tide', 'frost', 'prism', 'blaze', 'volt', 'phantom', 'stark']
# id: (name, kind, stops)
STYLES = [
    ('glint_gold', 'glint', ['#FFA62E', '#FFD27A', '#FFF0C2']),
    ('heartbeat', 'heartbeat', ['#FF3D55', '#FF7A92', '#FFB3C4']),
    ('tide', 'tide', ['#2F6BFF', '#3FB0FF', '#5CF2FF']),
    ('frost', 'frost', ['#A6E4FF', '#D6F4FF', '#FFFFFF']),
    ('prism', 'prism', ['#FF6B6B', '#FFD166', '#6BFF9E', '#6BC8FF']),
    ('blaze', 'blaze', ['#E8341C', '#FF7A2E', '#FFC94D']),
    ('volt', 'volt', ['#2FD8FF', '#8BEFFF', '#D9FBFF']),
    ('phantom', 'phantom', ['#9F7BFF', '#C7B0FF', '#ECE3FF']),
    ('glint_silver', 'glint', ['#AEB9C8', '#D8DFE8', '#F7F9FC']),
    ('glint_pink', 'glint', ['#E05CFF', '#F59BFF', '#FFD6FF']),
    # r86 rank exclusives (pack r43): SPARK = green electric strobes, STARK = slow gold shine + sparkles (own kind)
    ('spark_rank', 'volt', ['#21D982', '#6BFFBE', '#DFFFF0']),
    ('stark_rank', 'stark', ['#FF9A1A', '#FFCF57', '#FFF3C9']),
    # STORM = violet -> cyan waves rolling through (rank show title, STORM item names)
    ('storm_rank', 'tide', ['#7B5CFF', '#6A8CFF', '#3FD8FF']),
]
N = 8
def hx(h): h = h.lstrip('#'); return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))
def lerp(a, b, t): return tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))
def grad(stops, n):
    out = []
    for i in range(n):
        t = i / (n - 1) * (len(stops) - 1); k = min(int(t), len(stops) - 2)
        out.append(lerp(stops[k], stops[k + 1], t - k))
    return out
def used_colors():
    s = set()
    files = glob.glob('/home/claude/sc/work/src/main/resources/*.yml') + glob.glob('/mnt/user-data/uploads/FFA Minecraft Server/control/results/gem01_*.yml')
    for f in files:
        for m in re.finditer(r'#([0-9A-Fa-f]{6})\b', open(f, encoding='utf-8', errors='ignore').read()):
            s.add(hx(m.group(1)))
    for v in (0x00, 0x55, 0xAA, 0xFF):
        for w in (0x00, 0x55, 0xAA, 0xFF):
            for x in (0x00, 0x55, 0xAA, 0xFF): s.add((v, w, x))
    for v in (0x40, 0xA0, 0xE0, 0x80, 0x3F, 0x15, 0x2A, 0x3E, 0x7F, 0xFE, 0x10, 0x20, 0x30): s.add((v, v, v))
    return s
def build():
    used = used_colors(); taken = set()
    table = []
    for sid, (name, kind, stops) in enumerate(STYLES):
        cols = grad([hx(c) for c in stops], N)
        row = []
        for c in cols:
            # unusual low bits (r&3=1, g&3=2, b&3=3) + unique + never one of the colours in the configs
            for bump in range(0, 64):
                cand = tuple(max(0, min(255, (c[i] & ~3) | (1, 2, 3)[i])) for i in range(3))
                cand = (cand[0], cand[1], max(3, min(255, cand[2] - 4 * (bump // 2) * (1 if bump % 2 else -1))))
                cand = (cand[0], cand[1], (cand[2] & ~3) | 3)
                if cand not in used and cand not in taken: break
            taken.add(cand); row.append(cand)
        table.append((name, KINDS.index(kind), row))
    return table
def glsl(table):
    pal = ',\n    '.join(', '.join('ivec3(%d, %d, %d)' % c for c in row) for _, _, row in table)
    kinds = ', '.join(str(k) for _, k, _ in table)
    return ('const int STARK_STYLES = %d;\nconst int STARK_KIND[%d] = int[%d](%s);\nconst ivec3 STARK_PAL[%d] = ivec3[%d](\n    %s\n);\n'
            % (len(table), len(table), len(table), kinds, len(table) * N, len(table) * N, pal))
def java(table):
    lines = []
    for name, k, row in table:
        lines.append('            {%s}' % ', '.join('0x%02X%02X%02X' % c for c in row))
    return ('    /** Generated by gemshop/proto/palette.py - must match the pack r40 shader table. */\n'
            '    static final String[] STYLE_IDS = {%s};\n    static final int[][] PALETTE = {\n%s\n    };\n'
            % (', '.join('"%s"' % n for n, _, _ in table), ',\n'.join(lines)))
if __name__ == '__main__':
    t = build()
    for n, k, row in t: print(n, KINDS[k], ' '.join('#%02X%02X%02X' % c for c in row))
    open('/home/claude/gemshop/proto/palette.glsl', 'w').write(glsl(t))
    open('/home/claude/gemshop/proto/palette.java.txt', 'w').write(java(t))
    json.dump([[n, k, ['#%02X%02X%02X' % c for c in row]] for n, k, row in t], open('/home/claude/gemshop/proto/palette.json', 'w'))
    print('used colours checked:', len(used_colors()))
